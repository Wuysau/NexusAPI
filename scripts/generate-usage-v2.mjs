import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'
import prettier from 'prettier'

const root = fileURLToPath(new URL('../', import.meta.url))
const schema = JSON.parse(
  readFileSync(new URL('../packages/contracts/schemas/usage-event-v2.schema.json', import.meta.url), 'utf8'),
)
function tsType(node) {
  if ('const' in node) return JSON.stringify(node.const)
  if (node.enum) return node.enum.map((value) => JSON.stringify(value)).join(' | ')
  if (node.type === 'object')
    return `{\n${Object.entries(node.properties)
      .map(([key, child]) => `${key}${node.required?.includes(key) ? '' : '?'}: ${tsType(child)}`)
      .join('\n')}\n}`
  return []
    .concat(node.type)
    .map((type) => ({ integer: 'number', null: 'null', string: 'string', boolean: 'boolean' })[type])
    .join(' | ')
}
const ts = `// Generated by scripts/generate-usage-v2.mjs; edit the canonical JSON schema.\nexport const usageEventV2Schema = ${JSON.stringify(schema, null, 2)} as const\nexport type NexusUsageEventV2 = ${tsType(schema)}\n`
const config = await prettier.resolveConfig(root + 'package.json')
const formattedTS = await prettier.format(ts, { ...config, parser: 'typescript' })
const declarations = []
function goType(node, name) {
  if (node.type === 'object') {
    const fields = Object.entries(node.properties).map(([key, child]) => {
      const field = key
        .split('_')
        .map((part) => part[0].toUpperCase() + part.slice(1))
        .join('')
      return `${field} ${goType(child, name + field)} \`json:"${key}${node.required?.includes(key) ? '' : ',omitempty'}"\``
    })
    declarations.push(`type ${name} struct {\n${fields.join('\n')}\n}`)
    return name
  }
  if ('const' in node) return typeof node.const === 'number' ? 'int' : 'string'
  if (node.enum) return 'string'
  const types = [].concat(node.type)
  return (
    (types.includes('null') ? '*' : '') +
    { integer: 'int64', string: 'string', boolean: 'bool' }[types.find((t) => t !== 'null')]
  )
}
goType(schema, 'UsageEventV2')
const go = `// Code generated by scripts/generate-usage-v2.mjs; DO NOT EDIT.\npackage main\n\nconst usageEventV2CanonicalSchema = \`${JSON.stringify(schema)}\`\n\n${declarations.join('\n\n')}\n`
const checking = process.argv.includes('--check')
// Pure Node contract CI can verify Go tokens without installing the compiler.
// Whitespace inside quoted strings (including the embedded schema) is preserved.
const goTokens = (source) => JSON.stringify(source.match(/`[^`]*`|"(?:\\.|[^"\\])*"|[A-Za-z_]\w*|\d+|[^\s]/g))
const formattedGo = checking ? go : execFileSync('gofmt', { input: go, encoding: 'utf8' })
for (const [path, content] of [
  ['packages/contracts/usage-event-v2.generated.ts', formattedTS],
  ['services/gateway/contracts_v2_generated.go', formattedGo],
]) {
  const target = root + path
  if (checking) {
    const normalize = path.endsWith('.go') ? goTokens : (source) => source.replaceAll('\r\n', '\n')
    if (normalize(readFileSync(target, 'utf8')) !== normalize(content))
      throw new Error(`${path} is stale; run node scripts/generate-usage-v2.mjs`)
  } else writeFileSync(target, content)
}
